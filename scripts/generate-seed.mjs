// Generates supabase/seed.sql from the sample catalogue, so a new Supabase project starts with the same products the
// storefront shows in demo mode. Run it after changing src/lib/catalogue/sample.ts:  node scripts/generate-seed.mjs
import fs from "node:fs";
import { fileURLToPath } from "node:url";
import { availabilityToDb, slugify, audienceToDb } from "../src/lib/catalogue/build.ts";
import { sampleDefs, variantsOf } from "../src/lib/catalogue/sample.ts";
import { articles } from "../src/lib/data.ts";

const q = (v) => (v === null || v === undefined ? "null" : `'${String(v).replace(/'/g, "''")}'`);
const arr = (list) => (list.length ? `array[${list.map(q).join(", ")}]::text[]` : "'{}'::text[]");

const out = [];
out.push("-- GENERATED by scripts/generate-seed.mjs from src/lib/catalogue/sample.ts. Do not edit by hand.");
out.push("-- Loads the sample catalogue. Safe to run more than once. Prices marked sample are defaults until the owner confirms them.");
out.push("-- Run it AFTER the migrations. Skip it if you would rather start with an empty catalogue and import your own.\n");

out.push("insert into public.suppliers (name, notes) values ('Supplier A', 'Sample supplier'), ('Supplier B', 'Sample supplier') on conflict (name) do nothing;\n");

for (const d of sampleDefs) {
  const catSlug = slugify(d.subcategory ? `${d.category} ${d.subcategory}` : d.category);
  out.push(`-- ${d.name}`);
  out.push(
    `insert into public.products (slug, sku, name, brand, category_id, audience, description, details, is_new, popular, published, art)\n` +
      `select ${q(d.slug)}, ${q(d.sku)}, ${q(d.name)}, ${q(d.brand)}, c.id, ${q(audienceToDb(d.audience))}::public.audience, ${q(d.description)}, ${arr(d.details)}, ${!!d.isNew}, ${d.popular}, true, ${q(JSON.stringify(d.art))}::jsonb\n` +
      `from public.categories c where c.slug = ${q(catSlug)}\n` +
      `on conflict (slug) do nothing;`,
  );
  const rows = variantsOf(d).map(
    (v) =>
      `(${v.style ? q(v.style) : "null::text"}, ${q(v.colour)}, ${q(v.size)}, ${q(v.sku)}, ${v.price}, ${v.compareAt ?? "null::numeric"}, ${q(availabilityToDb(v.availability))}::public.availability, ${v.leadDays})`,
  );
  out.push(
    `insert into public.variants (product_id, style, colour, size, sku, price, compare_at, availability, lead_days, preferred_supplier_id)\n` +
      `select p.id, v.style, v.colour, v.size, v.sku, v.price, v.compare_at, v.availability, v.lead_days, (select id from public.suppliers where name = 'Supplier A')\n` +
      `from public.products p, (values\n  ${rows.join(",\n  ")}\n) as v (style, colour, size, sku, price, compare_at, availability, lead_days)\n` +
      `where p.slug = ${q(d.slug)}\n` +
      `on conflict (sku) do nothing;\n`,
  );
}

out.push("-- Drip School starter articles. Their layout is built into the shop, so they have no body here. Edit or replace them in the dashboard.");
for (const a of articles) {
  out.push(
    `insert into public.articles (slug, title, type, minutes, intro, tone, kind, status, publish_at, author_name)
` +
      `values (${q(a.slug)}, ${q(a.title)}, ${q(a.type)}, ${a.minutes}, ${q(a.intro)}, ${q(a.tone)}, ${q(a.kind)}, 'published', now(), 'Drezzy Team')
` +
      `on conflict (slug) do nothing;`,
  );
}
out.push("");

const target = fileURLToPath(new URL("../supabase/seed.sql", import.meta.url));
fs.writeFileSync(target, out.join("\n") + "\n");
console.log(`Wrote ${target} (${sampleDefs.length} products, ${articles.length} articles, ${sampleDefs.reduce((n, d) => n + variantsOf(d).length, 0)} variants)`);
